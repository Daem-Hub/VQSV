const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const path = require('path');
const html = fs.readFileSync(path.join(__dirname, '../prototype/index.html'), 'utf8');
const code = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].at(-1)[1].replace(/    loadData\(\)\.catch\(err => \{[^\n]+\}\);/, '');
let clock = 1000, cropX = null, cropY = null, drawX = null;
const ctx = new Proxy({ drawImage: (...args) => { if (args.length === 9) { cropX = args[1]; cropY = args[2]; drawX = args[5]; } } }, { get: (t,k) => k in t ? t[k] : () => {}, set: (t,k,v) => (t[k] = v, true) });
const els = {};
const element = id => els[id] ||= { textContent:'', hidden:false, addEventListener() {}, getContext: () => ctx };
const context = vm.createContext({document:{getElementById:element}, window:{addEventListener() {},VQSVBootstrap:require('./bootstrap_for_tests.cjs')}, Element:class {}, performance:{now:()=>clock}, console});
vm.runInContext(code, context);
vm.runInContext('assets.map={width:8,height:4,objects:[{solid:[[4,1]]}],entities:{player:{x:1,y:1},elder:{x:7,y:3},encounter:{x:7,y:2}}}; reset(); setMove(1,0)',context);
clock += 110; vm.runInContext('updatePlayer(performance.now())',context);
assert.equal(vm.runInContext('state.player.visualX',context), 1.5);
vm.runInContext('drawCharacter({width:400,height:400},state.player.visualX,state.player.visualY,"player",1,0)',context);
assert.equal(cropX,310);
assert.equal(cropY,690);
clock += 120; vm.runInContext('updatePlayer(performance.now())',context);
assert(Math.abs(vm.runInContext('state.player.visualX',context) - (2 + 10/220)) < 1e-9);
clock += 430; vm.runInContext('updatePlayer(performance.now())',context);
assert.equal(vm.runInContext('state.player.visualX',context), 3);
assert.equal(vm.runInContext('state.player.inputDir',context), null);
assert.equal(vm.runInContext('state.player.step',context), null);
vm.runInContext('drawCharacter({width:400,height:400},3,1,"player",1,0)',context);
assert.equal(cropX,50);
vm.runInContext('state.player.step={}; state.player.walkDistance=1.5; drawCharacter({width:400,height:400},3,1,"player",-1,0)',context);
assert.equal(cropX,830);
assert.equal(cropY,370);
assert.equal(drawX,-17);
vm.runInContext('drawCharacter({width:400,height:400},3,1,"player",0,1)',context);
assert.equal(cropX,830);
assert.equal(cropY,50);
console.log('Movement: slower timing, distance-based frames, continuous tile crossing and collision passed.');
